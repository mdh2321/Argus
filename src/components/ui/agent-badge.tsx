import { relativeTime } from "@/lib/utils";
import { workflowLabel, type Workflow } from "@/lib/agent-workflows";

interface AgentBadgeProps {
  workflow: Workflow | string | null | undefined;
  timestamp?: string | null;
  className?: string;
}

/**
 * Attribution badge for AI-generated artefacts.
 * Renders: "Sentinel · {Workflow} · {relative time}"
 */
export function AgentBadge({ workflow, timestamp, className = "" }: AgentBadgeProps) {
  const label = workflowLabel(workflow);
  const when = timestamp ? relativeTime(timestamp) : null;
  const title = timestamp
    ? `Generated by Sentinel (${label}) on ${new Date(timestamp).toLocaleString()}`
    : `Generated by Sentinel (${label})`;

  return (
    <span
      className={`inline-flex items-center gap-1.5 font-mono text-[10px] tracking-[0.04em] uppercase text-fg-3 ${className}`}
      title={title}
    >
      <span className="inline-block h-1.5 w-1.5 rounded-full bg-accent" />
      <span>Sentinel</span>
      <span className="text-fg-3/60">·</span>
      <span>{label}</span>
      {when && (
        <>
          <span className="text-fg-3/60">·</span>
          <span>{when}</span>
        </>
      )}
    </span>
  );
}
